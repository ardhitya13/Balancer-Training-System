import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { createRequire } from "node:module";
import ts from "typescript";

const require = createRequire(import.meta.url);
const cache = new Map();
function load(filename) {
  if (cache.has(filename)) return cache.get(filename).exports;
  const module = { exports: {} };
  cache.set(filename, module);
  const code = ts.transpileModule(fs.readFileSync(filename, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  vm.runInThisContext(`(function(require,module,exports){${code}\n})`, { filename })(
    (id) => id.startsWith(".") ? load(path.resolve(path.dirname(filename), `${id}.ts`)) : require(id), module, module.exports);
  return module.exports;
}
function storage() {
  const values = new Map();
  return { getItem: (key) => values.get(key) ?? null, setItem: (key, value) => values.set(key, String(value)), removeItem: (key) => values.delete(key) };
}

test("frontend demo accounts, permissions, progress, scores and account resets", async () => {
  globalThis.localStorage = storage();
  globalThis.sessionStorage = storage();
  globalThis.window = new EventTarget();
  const root = path.resolve(import.meta.dirname, "../src/lib/training");
  const store = load(path.join(root, "training-store.ts"));
  const { lessons } = load(path.resolve(root, "../../data/training/learning-content.ts"));
  const { practiceQuestions } = load(path.resolve(root, "../../data/training/practice-data.ts"));
  assert.equal(await store.getSession(), null);
  await assert.rejects(store.login("2260156", "incorrect"));
  const participant = await store.login("2260156", "2260156");
  assert.equal(participant.role, "trainee");
  assert.equal(participant.passwordHash, undefined);
  await assert.rejects(store.listUsers(), /khusus admin/);
  await assert.rejects(store.createUser({ name: "Invalid", id_card: "1234", password: "1234567" }));
  await assert.rejects(store.completeLesson(lessons[0].id, -1));
  await store.completeLesson(lessons[0].id, lessons[0].answer);
  await store.completeLesson(lessons[0].id, lessons[0].answer);
  assert.deepEqual((await store.getLearning()).completed, [lessons[0].id]);
  await assert.rejects(store.submitAttempt([], "incomplete"));
  const result = await store.submitAttempt(practiceQuestions.map((q) => q.answer), "attempt-1");
  assert.equal(result.score, 100);
  assert.equal((await store.submitAttempt(practiceQuestions.map((q) => q.answer), "attempt-1")).id, result.id);
  assert.equal((await store.getLearning()).attempts.length, 1);
  await store.logout();
  await store.login("admin", "admin123");
  assert.equal((await store.listUsers())[0].best_score, 100);
  await store.createUser({ name: "Peserta Baru", id_card: "2260157", password: "pass1234" });
  await assert.rejects(store.createUser({ name: "Duplikat", id_card: "2260157", password: "pass1234" }), /sudah terdaftar/);
  const newUser = (await store.listUsers()).find((u) => u.id_card === "2260157");
  await store.logout();
  await store.login("2260157", "pass1234");
  assert.deepEqual(await store.getLearning(), { completed: [], attempts: [] });
  const oldSession = sessionStorage.getItem("balancer-training.session.v1");
  await store.logout();
  await store.login("admin", "admin123");
  await store.updateUser(newUser.id, { name: "Peserta Baru", is_active: false });
  await assert.rejects(store.login("2260157", "pass1234"));
  await store.updateUser(newUser.id, { name: "Peserta Baru", is_active: true, password: "newpass123" });
  await store.logout();
  sessionStorage.setItem("balancer-training.session.v1", oldSession);
  assert.equal(await store.getSession(), null);
  await assert.rejects(store.login("2260157", "pass1234"));
  assert.equal((await store.login("2260157", "newpass123")).id, newUser.id);
  await store.logout();
  await store.login("2260156", "2260156");
  assert.equal((await store.getLearning()).attempts[0].score, 100);
  const stored = localStorage.getItem("balancer-training.frontend.v1");
  assert.equal(stored.includes("admin123"), false);
  assert.equal(stored.includes("newpass123"), false);
  const realSet = localStorage.setItem;
  localStorage.setItem = () => { throw new Error("quota"); };
  await assert.rejects(store.completeLesson(lessons[1].id, lessons[1].answer), /belum tersimpan/);
  localStorage.setItem = realSet;
  assert.equal((await store.getLearning()).completed.includes(lessons[1].id), false);

  const originalContent = store.getTrainingContent();
  await assert.rejects(async () => store.saveTrainingContent(originalContent), /khusus admin/);
  await store.logout();
  await store.login("admin", "admin123");
  const edited = structuredClone(originalContent);
  edited.lessons[0].title = "Materi diperbarui admin";
  edited.lessons[0].question = "Soal revisi admin?";
  edited.lessons[0].answer = (edited.lessons[0].answer + 1) % 4;
  edited.extraQuestions[0].answer = (edited.extraQuestions[0].answer + 1) % 4;
  const saved = store.saveTrainingContent(edited);
  assert.equal(saved.revision, 1);
  assert.equal(store.getTrainingContent().lessons[0].title, "Materi diperbarui admin");
  assert.equal(store.contentQuestions(saved)[0].question, "Soal revisi admin?");
  assert.throws(() => store.saveTrainingContent(originalContent), /diperbarui/);
  const invalid = structuredClone(saved);
  invalid.extraQuestions[0].options[1] = invalid.extraQuestions[0].options[0];
  assert.throws(() => store.saveTrainingContent(invalid), /pilihan berbeda/);
  assert.equal(store.getTrainingContent().revision, 1);
  localStorage.setItem = () => { throw new Error("quota"); };
  assert.throws(() => store.saveTrainingContent(saved), /belum tersimpan/);
  localStorage.setItem = realSet;
  assert.equal(store.getTrainingContent().revision, 1);
  await store.logout();
  await store.login("2260156", "2260156");
  assert.equal((await store.getLearning()).completed.includes(lessons[0].id), false);
  assert.equal((await store.getLearning()).attempts[0].score, 100);
  await assert.rejects(store.completeLesson(lessons[0].id, lessons[0].answer, 0), /diperbarui/);
  await assert.rejects(store.completeLesson(lessons[0].id, lessons[0].answer, 1), /belum tepat/);
  await store.completeLesson(lessons[0].id, saved.lessons[0].answer, 1);
  await assert.rejects(store.submitAttempt(practiceQuestions.map((q) => q.answer), "outdated", 0), /diperbarui/);
  const newAnswers = store.contentQuestions(store.getTrainingContent()).map((q) => q.answer);
  assert.equal((await store.submitAttempt(newAnswers, "revised", 1)).score, 100);
  assert.equal((await store.getLearning()).attempts.length, 2);

  const { legacyStandardLesson, standardLesson } = load(path.resolve(root, "../../data/training/standard-lesson.ts"));
  const key = "balancer-training.frontend.v1";
  const oldData = JSON.parse(localStorage.getItem(key));
  const standardIndex = oldData.content.lessons.findIndex((lesson) => lesson.id === "standard");
  oldData.content.lessons[standardIndex] = legacyStandardLesson;
  oldData.completed[1].push("standard");
  localStorage.setItem(key, JSON.stringify(oldData));
  const migrated = store.getTrainingContent();
  assert.deepEqual(migrated.lessons[standardIndex], standardLesson);
  assert.equal(migrated.revision, oldData.content.revision + 1);
  assert.equal((await store.getLearning()).completed.includes("standard"), false);
  assert.equal(store.getTrainingContent().revision, migrated.revision);
  const customized = JSON.parse(localStorage.getItem(key));
  customized.content.lessons[standardIndex] = { ...legacyStandardLesson, summary: "Materi standar khusus dari admin" };
  localStorage.setItem(key, JSON.stringify(customized));
  assert.equal(store.getTrainingContent().lessons[standardIndex].summary, "Materi standar khusus dari admin");

  const priorContent = JSON.parse(localStorage.getItem(key));
  priorContent.content.lessons = priorContent.content.lessons.filter((lesson) => !["rework", "product-quantity"].includes(lesson.id));
  const priorTitle = priorContent.content.lessons[0].title;
  const priorExtra = structuredClone(priorContent.content.extraQuestions);
  const priorRevision = priorContent.content.revision;
  localStorage.setItem(key, JSON.stringify(priorContent));
  const extended = store.getTrainingContent();
  assert.equal(extended.lessons.find((lesson) => lesson.id === "rework").answer, 0);
  assert.ok(extended.lessons.some((lesson) => lesson.id === "product-quantity"));
  assert.equal(extended.lessons[0].title, priorTitle);
  assert.deepEqual(extended.extraQuestions, priorExtra);
  assert.equal(extended.revision, priorRevision + 1);
  assert.equal(store.getTrainingContent().revision, extended.revision);
  await store.logout();
  await store.login("admin", "admin123");
  assert.equal(store.saveTrainingContent(extended).revision, extended.revision + 1);
});
